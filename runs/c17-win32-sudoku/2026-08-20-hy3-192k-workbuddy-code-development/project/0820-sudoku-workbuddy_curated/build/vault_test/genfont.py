# Sanity: ensure all printable ASCII 32..126 have an entry (lowercase -> uppercase)
order = []
seen = set()
def emit(ch):
    if ch in seen: return
    seen.add(ch)
    order.append(ch)

# first emit the defined glyphs in ASCII order
allchars = [chr(c) for c in range(32,127)]
for ch in allchars:
    if ch in G:
        emit(ch)
# lowercase a-z map to uppercase
for c in range(ord('a'), ord('z')+1):
    up = chr(c-32)
    if up in G and chr(c) not in G:
        G[chr(c)] = G[up]
        emit(chr(c))
# fallback box for anything still missing
for ch in allchars:
    if ch not in G:
        G[ch] = ["#####","#...#","#...#","#...#","#...#","#...#","#####"]
        emit(ch)

# Emit C source
lines = []
lines.append("/* auto-generated 5x7 bitmap font (see build/vault_test/genfont.py). */")
lines.append("#ifndef SDK_UI_FONT_DATA_H")
lines.append("#define SDK_UI_FONT_DATA_H")
lines.append("#include <stdint.h>")
lines.append("")
lines.append("/* glyphs in ASCII order 32..126, each 7 rows of 5 bits (MSB left). */")
lines.append("static const uint8_t SDK_FONT_5X7[95][7] = {")
for i, ch in enumerate(order):
    rows = G[ch]
    bits = []
    for r in rows:
        v = 0
        for bit in r:
            v = (v<<1) | (1 if bit == '#' else 0)
        bits.append(v)
    lines.append("  { %s }, /* %s */" % (", ".join("%3d" % b for b in bits), repr(ch)[1:-1]))
lines.append("};")
lines.append("#endif")
src = "\n".join(lines)
out_root = r"D:\0820-sudoku-workbuddy"
open(out_root + r"\include\ui\sdk_ui_font_data.h","w").write(src)
open(out_root + r"\src\ui\sdk_ui_font_data.h","w").write(src)
print("wrote", len(order), "glyphs")
